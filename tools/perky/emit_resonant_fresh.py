#!/usr/bin/env python3
"""Regenerate modules/perky/resonant_fresh.py -- the authentic fresh voice state.

Runs the exact v1.2.1 init/update/trigger recovery (modules/perky/
resonant_control_update.py, translated from the ARM routines: bass
0x08026790 / 0x0802682C / 0x080268DC, snare 0x08025F8C / 0x08026030 / 0x08026108,
shared 0x080246AC / 0x08024714 / 0x08024878) at a NEUTRAL control setting, then
maps the ARM-shaped object into the compact renderer layout with the model's own
`from_arm` -- so the words are the renderer's, derived by the renderer's own code.

Needs the shared PERKONS tables. They are build outputs of the perky-optimize
worktree, not committed (nothing Elektron ships is redistributed here):

    out/perky/res-assets/{pitch.bin,chromatic.bin}

`note_offset()` reads chromatic; `common_update()` reads pitch. Both come from
the firmware image the captures were recorded from.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT), str(ROOT / "modules/perky")]

import resonant_bass_compact as bass            # noqa: E402
import resonant_control_update as rcu           # noqa: E402
import resonant_snare_compact as snare          # noqa: E402

ASSETS = ROOT / "out/perky/res-assets"
TARGETS = (2048, 2048, 2048, 2048)     # neutral panel setting
VELOCITY, NOTE = 255, 45
OUT = ROOT / "modules/perky/resonant_fresh.py"
OUT_H = ROOT / "modules/perky/resonant_fresh.h"


def main() -> None:
    pitch = (ASSETS / "pitch.bin").read_bytes()
    chrom = (ASSETS / "chromatic.bin").read_bytes()
    if len(pitch) != 4096 * 2 or len(chrom) != 12 * 2:
        raise SystemExit(f"shared tables look wrong: pitch {len(pitch)} B, "
                         f"chromatic {len(chrom)} B -- run "
                         f"verify_perky_cf_final.py in perky-optimize once")

    b = rcu.trigger_bass(
        rcu.update_bass(rcu.fresh_bass(VELOCITY, NOTE), TARGETS, pitch, chrom),
        VELOCITY, NOTE)
    s = rcu.trigger_snare(
        rcu.update_snare(rcu.fresh_snare(VELOCITY, NOTE), TARGETS, pitch, chrom),
        VELOCITY, NOTE)
    # The bass update writes past 0x178 (to 0x17C); only 0x178 is compared
    # against the bass captures, so the from_arm width is 0x178.
    bw = list(bass.ResonantBass.from_arm(bytes(b[:0x178])).words)
    sw = list(snare.ResonantSnare.from_arm(bytes(s)).words)

    OUT.write_text(
        '"""GENERATED by tools/perky/emit_resonant_fresh.py -- do not hand-edit.\n\n'
        'The authentic fresh voice state for the two Resonant engines, produced by\n'
        'the exact v1.2.1 init/update/trigger recovery (modules/perky/\n'
        'resonant_control_update.py; ARM bass 0x08026790/0x0802682C/0x080268DC,\n'
        'snare 0x08025F8C/0x08026030/0x08026108, shared 0x080246AC/0x08024714/\n'
        '0x08024878) at a NEUTRAL control setting (2048,2048,2048,2048), velocity\n'
        '255, note 45, then mapped to the compact renderer layout by the model\'s own\n'
        '`from_arm`.\n\n'
        'WHY THIS EXISTS. The DSP renders from X:0x3800 and NOTHING initialised it.\n'
        'A zero voice block is silent BY THE ALGORITHM -- `ResonantSnare([0]*WORDS)`\n'
        'and `ResonantBass([0]*WORDS)` produce a peak of 0 over 64 blocks in the\n'
        'reference model itself -- so the resonant engines were silent on hardware\n'
        'for the same reason, not because of a port defect.\n\n'
        'These words ARE the state a freshly selected engine must start from. What\n'
        'is still missing is the PRODUCTION PATH that delivers them; see\n'
        '"THE RESONANT STATE IS NEVER INITIALISED" in modules/perky/DSP_3ALGO.md for\n'
        'the three candidate routes and their measured word budgets.\n"""\n\n'
        f'BASS_WORDS = {bw!r}\n\n'
        f'SNARE_WORDS = {sw!r}\n')
    def carr(name, words):
        rows = [words[i:i + 8] for i in range(0, len(words), 8)]
        body = ',\n    '.join(', '.join(f'0x{v:04x}' for v in r) for r in rows)
        return (f'/* {name}: {len(words)} compact words, sent DENSE and copied in '
                f'order by the DSP. */\n'
                f'static const unsigned short PK_RES_FRESH_{name}[{len(words)}] = '
                f'{{\n    {body}\n}};\n'
                f'#define PK_RES_FRESH_{name}_WORDS {len(words)}\n')

    OUT_H.write_text(
        '/* GENERATED by tools/perky/emit_resonant_fresh.py -- do not hand-edit.\n'
        ' *\n'
        ' * The authentic fresh voice state for the Resonant engines, from the exact\n'
        ' * v1.2.1 init/update/trigger recovery (ARM bass 0x08026790/0x0802682C/\n'
        ' * 0x080268DC, snare 0x08025F8C/0x08026030/0x08026108, shared 0x080246AC/\n'
        ' * 0x08024714/0x08024878) at a neutral control setting, velocity 255, note\n'
        ' * 45, mapped to the compact layout by the model\'s own from_arm.\n'
        ' *\n'
        ' * The DSP renders from X:0x3800 and NOTHING initialised it; a ZERO block is\n'
        ' * silent BY THE ALGORITHM (`ResonantSnare([0]*WORDS)` peaks at 0 over 64\n'
        ' * blocks in the reference model itself). These cross the record buffer,\n'
        ' * whose per-track stride is 336 bytes and which the 20-word record uses only\n'
        ' * 40 bytes of.\n'
        ' */\n'
        '#ifndef OCTABAM_PERKY_RESONANT_FRESH_H\n'
        '#define OCTABAM_PERKY_RESONANT_FRESH_H\n\n'
        + carr('BASS', bw) + '\n' + carr('SNARE', sw) + '\n#endif\n')
    print(f"wrote {OUT.relative_to(ROOT)} and {OUT_H.relative_to(ROOT)}: "
          f"bass {len(bw)} words, snare {len(sw)} words")


if __name__ == "__main__":
    main()
