VERSION=os.environ.get('PERKY_BUDGET_VERSION','PKFM7')

def taps(text):
 start=text.index('static void nhr_emit(')
 begin=text.index('    for(unsigned i=0;i<need;i++){',start)
 end=text.index('\n}\n',begin)
 old=text[begin:end]
 replacement='''    if(need && need<=20 && nht_ring_index<4805 &&
       nht_issued-nht_committed<=0xffffffffu-need && nhr_used+5*need<=168){
        unsigned pending=nht_issued-nht_committed,peak=pending+need-1;
        if(peak>pk_nht_pending_max)pk_nht_pending_max=peak;
        if(peak>=573)pk_nhr_failures+=pending>=573?need:peak-572;
        uint16_t last[5];
        nht_ring_index=pk_budget_gather_taps(t->nh+0x3f8,nhr_commands+nhr_used,nht_ring_index,need,last);
        if(nhb_building)for(unsigned k=0;k<5;k++)nhb_building->half[apply!=0].carry_taps[k]=last[k];
        nhr_used+=5*need;pk_nht_tap_words+=5*need;nht_issued+=need;
    }else{
'''+old+'\n    }'
 return ('extern unsigned pk_budget_gather_taps(const uint8_t*,uint16_t*,unsigned,unsigned,uint16_t*);\n'+text[:begin]+replacement+text[end:])

def main():
 WORK.mkdir(parents=True,exist_ok=True);card.W=WORK
 cf=card.a.b.G.h.CF;original=cf.build;old_module=cf.base.build_hybrid_module
 def module(*args,**kw):
  m=old_module(*args,**kw)
  return dataclasses.replace(m,linked=m.linked+(card.a.b.G.h.Linked('pkbudget','modules/perky/budget_transport.s',dram=True),))
 cf.base.build_hybrid_module=module
 def build(work,**kw):
  previous=kw.get('source_transform')
  def source(name,path):
   if name=='pkplacement' and os.environ.get('PERKY_BUDGET_CODEGEN'):
    option=os.environ['PERKY_BUDGET_CODEGEN'];assert option in ('O2','Os','O3')
    out=WORK/'placement-bounded-codegen.c';out.write_text(f'#pragma GCC optimize ("{option}","no-unroll-loops","no-peel-loops","no-tree-loop-distribute-patterns")\n'+Path(path).read_text());return out
   if name=='pkslap' and os.environ.get('PERKY_BUDGET_SLAP')=='1':
    source=previous(name,path) if previous else path
    s=Path(source).read_text();start=s.index('int pk_cf_slap_render(');end=s.index('#else',start)
    body=s[start:end];assert body.count('    int32_t inner_block[20];')==1
    body=body.replace('    int32_t inner_block[20];','    int32_t inner_block[20],filtered[20];int16_t noise[20];')
    marker='    for(i=0;i<n;i++){';assert body.count(marker)==1
    body=body.replace(marker,'    for(i=0;i<n;i++)noise[i]=slap_noise_step(&ns,rng);\n    if(n)pk_budget_slap_filter(&fs,noise,filtered,n);\n'+marker)
    body=body.replace('        int16_t nv=slap_noise_step(&ns,rng);','')
    old='        slap_filter_step(&fs,(int32_t)nv);\n        slap_filter_step(&fs,(int32_t)nv);';assert body.count(old)==1
    body=body.replace(old,'').replace('scaled=asr(mullo(fs.first,(int32_t)a),16);','scaled=asr(mullo(filtered[i],(int32_t)a),16);')
    out=WORK/'slap-filter-block.c';out.write_text('#include <stdint.h>\nextern void pk_budget_slap_filter(void*,const int16_t*,int32_t*,unsigned);\n'+s[:start]+body+s[end:]);return out
   if name=='pkwavetable':
    s=Path(path).read_text();assert s.count('amplitudes[16];uint32_t steps[16]')==1
    s=s.replace('amplitudes[16];uint32_t steps[16]','amplitudes[20];uint32_t steps[20]')
    assert s.count('n>16u?16u:n')==1;s=s.replace('n>16u?16u:n','n>20u?20u:n')
    out=WORK/'wavetable-native20.c';out.write_text(s);return out
   if name=='pknhbinner':
    out=WORK/'hat-inner-transposed.c';metallic.generate(out);s=out.read_text()
    for old,new in [('    nh_delay_load(&dly,s);\n',''),('dst[i]=s16((uint16_t)nh_delay_step(s,&dly,inner));','dst[i]=(int16_t)inner;'),('w16(s,NH_IDX,(uint16_t)dly.index);','')]:
     assert s.count(old)==3,(old,s.count(old));s=s.replace(old,new)
    option=os.environ.get('PERKY_BUDGET_CODEGEN')
    prefix=f'#pragma GCC optimize ("{option}","no-unroll-loops","no-peel-loops","no-tree-loop-distribute-patterns")\n' if option else ''
    out.write_text(prefix+'#define pk_cf_nh_render pk_nhb_inner_renderer\n'+s);return out
   return previous(name,path) if previous else None
  kw['source_transform']=source;kw['version']=VERSION
