#!/usr/bin/env python3
"""Emit the tracked three-algorithm module from the working in-memory helper.

`tools/perky/build_dsp_3algo.py` upgrades the tiny tracked `PERKY PROBE`
declaration to the full machine **in memory only**, which means the canonical
build (`make bus REMIX=perky-dsp-3algo`) could not reproduce the deliverable:
it linked the probe canary's ColdFire side instead.

This script writes that same declaration out as a tracked module, plus the two
sources it names, so the canonical build produces the deliverable:

  modules/perky3algo/manifest.py      the declaration
  modules/perky/control_3algo.s       generate.py, defines=THREE_ALGORITHM_DEFINES
  modules/perky/machine_3algo.asm     build_dsp_3algo_source.compose(), @CONT@
                                      left in place for the build to substitute
                                      per payload

`verify_perky_3algo_control_join.check_generated_artifact` re-runs all three and
refuses on any difference, so the tracked copies cannot drift from their
generators.

Nothing here is hand-written: the manifest is the dataclass repr of the module
`perky_machine_module.build` returns, with the key/name changed so it can sit
beside the probe rather than shadow it, and with the DSP hook pointed at this
machine's own entry label.
"""
from __future__ import annotations

import dataclasses
import importlib.util
import re
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "modules/perky3algo/manifest.py"
CONTROL = ROOT / "modules/perky/control_3algo.s"
DSP = ROOT / "modules/perky/machine_3algo.asm"
# The composed entry point the DSP hook must name. The in-memory helper inherits
# the probe's `pk_probe_source`; the composition defines its own entry.
ENTRY_LABEL = "pk3d_source"


def _module(path: Path):
    module = types.ModuleType("emit_" + path.parent.name)
    module.__dict__["__file__"] = str(path)
    exec(compile(path.read_text(), str(path), "exec"), module.__dict__)
    return module


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _sorted_sets(text: str) -> str:
    """Canonicalise `frozenset` reprs.

    A frozenset's iteration order follows string hashing, which Python
    randomises per process -- so `frozenset({'A', 'B'})` reprs as
    `frozenset({'A', 'B'})` in one run and `frozenset({'B', 'A'})` in the next.
    Emitting that repr makes the generated manifest differ between runs for no
    reason, which the drift gate then (correctly) reports.
    """
    def one(match):
        items = sorted(i.strip() for i in match.group(1).split(",") if i.strip())
        return "frozenset({" + ", ".join(items) + "})"
    return re.sub(r"frozenset\(\{([^}]*)\}\)", one, text)


def _literal(obj) -> str:
    text = repr(obj)
    # dataclass reprs spell enums as `<Kind.HYBRID: 'hybrid'>` and dict-like
    # fields as `mappingproxy({...})`; neither is a Python expression.
    text = re.sub(r"<([A-Za-z_][A-Za-z_0-9]*)\.([A-Z_0-9]+): [^>]*>", r"\1.\2", text)
    text = text.replace("mappingproxy(", "(")
    return _sorted_sets(text)


def render() -> tuple[str, str, str]:
    sys.path[:0] = [str(ROOT), str(ROOT / "tools"),
                    str(ROOT / "modules/perky"), str(ROOT / "tools/perky")]
    import remix.schema as schema

    generate = _load("emit_generate", ROOT / "modules/perky/generate.py")
    composer = _load("emit_composer", ROOT / "tools/perky/build_dsp_3algo_source.py")
    machine = _load("emit_machine", ROOT / "tools/perky/perky_machine_module.py")

    control_text = generate.generate_text(defines=generate.THREE_ALGORITHM_DEFINES)
    # `@CONT@` is left in place: the build substitutes it per payload.
    dsp_text = composer.normalize(composer.compose())

    original = _module(ROOT / "modules/perky/manifest.py").MODULE
    upgraded = machine.build(original,
                             control_source="modules/perky/control_3algo.s",
                             dsp_source="modules/perky/machine_3algo.asm")

    names = sorted({n for n in re.findall(r"\b([A-Z][A-Za-z_0-9]*)\b", _literal(upgraded))
                    if hasattr(schema, n)})
    out = [
        '"""Reduced Perky three-algorithm machine: Fold / Resonant Bass / Resonant Snare.',
        "",
        "GENERATED by tools/perky/emit_3algo_manifest.py -- do not hand-edit.",
        "Regenerate with:  python3 tools/perky/emit_3algo_manifest.py",
        "",
        "Its two sources are generated too, and verify_perky_3algo_control_join",
        "re-runs all three generators and refuses on any difference:",
        "",
        "  modules/perky/control_3algo.s   <- generate.py, 3-algorithm defines",
        "  modules/perky/machine_3algo.asm <- build_dsp_3algo_source.compose()",
        '"""',
        "from remix.schema import (",
    ]
    for index in range(0, len(names), 4):
        out.append("    " + ", ".join(names[index:index + 4]) + ",")
    out += [")", "", "MODULE = Module("]
    for field in dataclasses.fields(upgraded):
        value = _literal(getattr(upgraded, field.name))
        out.append(f"    {field.name}={value},")
    out.append(")")
    text = "\n".join(out) + "\n"
    text = text.replace("name='perky'", "name='perky3algo'")
    text = text.replace("key='PERKY PROBE'", "key='PERKY 3ALGO'")
    text = text.replace("label='pk_probe_source'", f"label='{ENTRY_LABEL}'")
    compile(text, str(MANIFEST), "exec")
    return text, control_text, dsp_text


def main() -> None:
    manifest, control, dsp = render()
    for path, body in ((MANIFEST, manifest), (CONTROL, control), (DSP, dsp)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        print(f"wrote {path.relative_to(ROOT)} ({len(body)} B)")


if __name__ == "__main__":
    main()
