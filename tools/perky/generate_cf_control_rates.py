#!/usr/bin/env python3
"""Generate exact integer envelope rates; no firmware bytes or approximations."""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
CONFIGURATIONS=((5,4000),(2,4000),(50,7280))

def time_parameter(prepared):
    q=0x7fff+(prepared<<2)
    mant=(q&0xfff)+0x1000;exp=(q>>12)&15
    value=((mant<<(exp-12)) if exp>11 else (mant>>(12-exp)))&0xffff
    value=((value-1)&0xffffffff)>>1&0x7fff
    return (value-0x7f)&0xffff

def rate(off,scale,prepared):
    product=(48*((scale-1)&0xffff)*time_parameter(prepared))&0xffffffff
    denominator=(48*((off+1)&0xffff)+(product>>12))&0xffffffff
    return (0xfffff//denominator if denominator else 0)&0xffff

def smoothing_thresholds(n):
    groups=[]
    for delta in range(-4095,4096):
        value=delta
        for _ in range(n):value=5*value//8
        if not groups or groups[-1][1]!=value:groups.append((delta,value))
    return groups

def threshold_tree(groups,indent='    '):
    if len(groups)==1:return [indent+f'return {groups[0][1]};']
    middle=len(groups)//2;threshold=groups[middle][0]
    return ([indent+f'if(delta<{threshold}){{']+
            threshold_tree(groups[:middle],indent+'    ')+[indent+'}else{']+
            threshold_tree(groups[middle:],indent+'    ')+[indent+'}'])

def generate():
    lines=['/* Generated by tools/perky/generate_cf_control_rates.py from integer arithmetic. */',
           '#ifndef OCTABAM_PERKY_CF_CONTROL_RATES_H', '#define OCTABAM_PERKY_CF_CONTROL_RATES_H',
           '#include <stdint.h>',
           'static const uint16_t pk_cf_control_decay_rates[3][4096] = {']
    for off,scale in CONFIGURATIONS:
        values=[rate(off,scale,i) for i in range(4096)]
        lines.append(f'    {{ /* off={off}, scale={scale} */')
        for start in range(0,4096,16):lines.append('        '+','.join(map(str,values[start:start+16]))+',')
        lines.append('    },')
    lines+=['};', '/* Exact repeated floor(5*delta/8) for bounded control words. */']
    for n in (14,15,16):
        lines.append(f'static inline int32_t pk_cf_control_smooth_{n}(int32_t delta){{')
        lines+=threshold_tree(smoothing_thresholds(n));lines.append('}')
    lines+=['#endif','']
    return '\n'.join(lines)

if __name__=='__main__':
    import argparse
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true',help='Verify the committed header without modifying it')
    args=ap.parse_args();path=ROOT/'modules/perky/cf_control_rates.h'
    if args.check:
        assert path.read_text()==generate(), 'generated control arithmetic header drift'
        print('Exact generated control arithmetic: PASS')
    else:path.write_text(generate())
